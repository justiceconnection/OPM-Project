#!/usr/bin/env node
/* Writes web/assets/js/appointment-groups.js, the Look-Up's appointment-type mapping (D-095), from
   pipeline/crosswalks/appointment_groups.csv (D-086): OPM's published appointment_type label -> the
   Appointments tab's group, groups in group_order, labels in crosswalk row order. Rows with no display
   label (group 'unknown': INVALID) are listed on their own, as published. The browser never reads the CSV;
   web/tests/lookup.test.js checks the generated file equals the crosswalk exactly.

   Usage: node web/tools/build-appointment-groups.js [--check]
     --check  write nothing; exit 1 if the file on disk differs from what the crosswalk gives */
'use strict';
const fs = require('fs');
const path = require('path');

const WEB = path.resolve(__dirname, '..');
const REPO = path.resolve(WEB, '..');
const CSV = path.join(REPO, 'pipeline', 'crosswalks', 'appointment_groups.csv');
const OUT = path.join(WEB, 'assets', 'js', 'appointment-groups.js');

/* RFC 4180 rows (quoted fields may hold commas). */
function parseCsv(text) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(f); rows.push(row); row = []; f = ''; }
    else f += c;
  }
  if (f !== '' || row.length) { row.push(f); rows.push(row); }
  const [head, ...body] = rows.filter(r => r.some(v => v !== ''));
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] === undefined ? '' : r[i]])));
}

/* { groups: [{ group, labels: [...] }] in group_order, unknown: [labels with no display label] } */
function mapping(csvText = fs.readFileSync(CSV, 'utf8')) {
  const rows = parseCsv(csvText);
  const groups = [], byGroup = {}, unknown = [];
  rows.forEach(r => {
    if (!r.display_label) { unknown.push(r.opm_label); return; }
    if (!byGroup[r.group]) { byGroup[r.group] = { group: r.group, order: +r.group_order, labels: [] }; groups.push(byGroup[r.group]); }
    byGroup[r.group].labels.push(r.opm_label);
  });
  groups.sort((a, b) => a.order - b.order);
  return { groups: groups.map(g => ({ group: g.group, labels: g.labels })), unknown };
}

function render(m) {
  return '/* Generated by web/tools/build-appointment-groups.js from pipeline/crosswalks/appointment_groups.csv (D-086, D-095).\n' +
    '   Do not edit by hand: change the crosswalk and rerun the tool. web/tests/lookup.test.js checks they agree. */\n' +
    '(function (root, data) {\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = data;\n" +
    '  else { root.OPM = root.OPM || {}; root.OPM.appointmentGroups = data; }\n' +
    "})(typeof self !== 'undefined' ? self : this, " + JSON.stringify(m, null, 2) + ');\n';
}

if (require.main === module) {
  const text = render(mapping());
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error(path.relative(REPO, OUT) + ' differs from the crosswalk; run node web/tools/build-appointment-groups.js'); process.exit(1); }
    console.log(path.relative(REPO, OUT) + ' matches the crosswalk');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + path.relative(REPO, OUT));
  }
}

module.exports = { parseCsv, mapping, render, CSV, OUT };
